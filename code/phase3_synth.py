"""Phase 3 decisive experiment: recovery on synthetic ground truth.

Windows are generated by phase3_gen.make_synth (organisers' stated
process; background identity known but NOT given to the matchers).
Estimators compared on identical windows:
  oracle     subtraction with the TRUE background (ceiling for matching)
  matchA     Matcher A (KD-tree anchors) best candidate, subtraction
  matchB     Matcher B (grid-hash anchors) best candidate, subtraction
  quiet      per-window background = per-band 10th percentile across the
             window's own observed minutes; excess share
  stat_or    station-median spectrum of the TRUE site, level-aligned on
             the >=1 kHz bands; excess share
  stat_guess same but the site is guessed by profile fit (test has no
             site labels, so this is the deployable variant)
Splits: A = backgrounds from the 8 training sites; B = backgrounds from
the 2 holdout sites (Bird Island, Fish Hoek) — a disjoint split.
Seed 20261116. Nothing touches Test.csv here.
"""
import json
import numpy as np
from common import DATA, SEED, CENTRES, db_to_lin
from phase3_gen import make_synth, est_from_bg, BG_X, BG_SITE
from phase3_match import Matcher, HashMatcher, HB

SHARES = [0.0, 0.05, 0.1, 0.2, 0.35, 0.5, 0.7, 0.9]
HOLDOUT = {"4 Bird Island", "9 Fish Hoek"}
REPS = {"A": 15, "B": 10}

# ---- station profiles from the minute index (every 20th minute) ----
_d = np.load(DATA / "phase3_minutes.npz", allow_pickle=True)
_V, _site = _d["V"], _d["site"]
PROFILES = {}
for s in np.unique(_site):
    sel = _V[_site == s][::20].astype(np.float64)
    PROFILES[str(s)] = np.median(sel, axis=0)


def quiet_est(T_db, q=10.0):
    obs = np.isfinite(T_db)
    E = db_to_lin(np.where(obs, T_db, np.nan))
    with np.errstate(all="ignore"):
        bg = np.nanpercentile(E, q, axis=0)
    bg = np.where(np.isfinite(bg), bg, 0.0)
    Eo = np.where(obs, E, 0.0)
    tot = Eo.sum()
    return float(np.maximum(Eo - bg[None, :], 0.0).sum() / tot) if tot > 0 else 0.0


def stat_est(T_db, site=None):
    obs = np.isfinite(T_db)
    E = db_to_lin(np.where(obs, T_db, np.nan))
    with np.errstate(all="ignore"):
        med_T = np.nanmedian(np.where(obs, T_db, np.nan), axis=0)
    def fit(s):
        off = np.median((med_T - PROFILES[s])[HB])
        mis = np.median(np.abs((med_T - PROFILES[s] - off)[HB]))
        return off, mis
    if site is None:
        site = min(PROFILES, key=lambda s: fit(s)[1])
    off, _ = fit(site)
    bg_db = PROFILES[site] + off
    bg = db_to_lin(bg_db)
    Eo = np.where(obs, E, 0.0)
    tot = Eo.sum()
    return float(np.maximum(Eo - bg[None, :], 0.0).sum() / tot) if tot > 0 else 0.0


def main():
    r = np.random.default_rng(SEED)
    mA, mB = Matcher(), HashMatcher()
    poolA = np.where(~np.isin(BG_SITE, list(HOLDOUT)))[0]
    poolB = np.where(np.isin(BG_SITE, list(HOLDOUT)))[0]
    records = []
    for split, pool in (("A", poolA), ("B", poolB)):
        for s in SHARES:
            for _ in range(REPS[split]):
                bg_idx = int(pool[r.integers(len(pool))])
                win, info = make_synth(bg_idx, s, r)
                rec = dict(split=split, **info)
                rec["oracle"] = est_from_bg(win, BG_X[bg_idx].astype(np.float64))
                for name, m in (("matchA", mA), ("matchB", mB)):
                    top = m.match(win, topn=1, enrich=False)
                    if top:
                        c = top[0]
                        B = m.V[c["start_idx"]:c["start_idx"] + 15].astype(np.float64)
                        rec[name] = est_from_bg(win, B)
                        rec[name + "_viol"] = c["viol"]
                        rec[name + "_nexact"] = c["n_exact_min"]
                        rec[name + "_found"] = bool(
                            c["site"] == info["bg_site"] and c["t_start"] == info["bg_start"])
                    else:
                        rec[name] = np.nan
                        rec[name + "_viol"] = np.nan
                        rec[name + "_nexact"] = 0
                        rec[name + "_found"] = False
                # union of both generations, one verification (cross-check)
                ustarts = mA.candidate_starts(win) + mB.candidate_starts(win)
                utop = mA.verify(win, ustarts)
                if utop:
                    c = utop[0]
                    B = mA.V[c["start_idx"]:c["start_idx"] + 15].astype(np.float64)
                    rec["union"] = est_from_bg(win, B)
                    rec["union_viol"] = c["viol"]
                    rec["union_nexact"] = c["n_exact_min"]
                    rec["union_found"] = bool(
                        c["site"] == info["bg_site"] and c["t_start"] == info["bg_start"])
                else:
                    rec["union"] = np.nan
                    rec["union_viol"] = np.nan
                    rec["union_nexact"] = 0
                    rec["union_found"] = False
                rec["quiet"] = quiet_est(win)
                rec["stat_or"] = stat_est(win, site=info["bg_site"])
                rec["stat_guess"] = stat_est(win, site=None)
                records.append(rec)
                print(split, s, "true", round(info["true_share"], 3),
                      "A", None if np.isnan(rec["matchA"]) else round(rec["matchA"], 3),
                      "B", None if np.isnan(rec["matchB"]) else round(rec["matchB"], 3),
                      "foundA", rec["matchA_found"], "foundB", rec["matchB_found"],
                      flush=True)
    with open(DATA / "phase3_synth_records.json", "w") as f:
        json.dump(records, f)
    # ---- tables ----
    ests = ["oracle", "matchA", "matchB", "union", "quiet", "stat_or", "stat_guess"]
    def rmse(rs, e):
        v = np.array([x[e] for x in rs], dtype=np.float64)
        t = np.array([x["true_share"] for x in rs])
        ok = np.isfinite(v)
        return float(np.sqrt(np.mean((v[ok] - t[ok]) ** 2))) if ok.any() else np.nan
    for split in ("A", "B", "AB"):
        rs = records if split == "AB" else [x for x in records if x["split"] == split]
        print(f"\n== split {split} (n={len(rs)}) overall ==")
        for e in ests:
            print(f"  {e:10s} RMSE {rmse(rs, e):.4f}  score {1 - rmse(rs, e):.4f}")
    print("\n== RMSE by share level (splits combined) ==")
    print("share  " + "  ".join(f"{e:>9s}" for e in ests))
    for s in SHARES:
        rs = [x for x in records if x["target_share"] == s]
        print(f"{s:5.2f}  " + "  ".join(f"{rmse(rs, e):9.4f}" for e in ests))
    both = [x for x in records if np.isfinite(x["matchA"]) and np.isfinite(x["matchB"])]
    d = np.array([x["matchA"] - x["matchB"] for x in both])
    print(f"\nA vs B agreement: n={len(both)}, mean|diff| {np.abs(d).mean():.4f}, "
          f"RMSE between estimates {np.sqrt((d ** 2).mean()):.4f}")
    print("found true bg: A", np.mean([x["matchA_found"] for x in records]),
          " B", np.mean([x["matchB_found"] for x in records]),
          " union", np.mean([x["union_found"] for x in records]))


if __name__ == "__main__":
    main()
