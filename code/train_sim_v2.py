"""Train the simulator-v2 model (LightGBM) and validate per PLAN.md 4.5.

Differences vs train_sim_v1.py (the Phase 2 training fixes):
  - num_boost_round cap raised 1500 -> 6000 and early-stopping patience
    100 -> 200, against the same internal 90/10 split of the training set.
    (v1's best iteration WAS the 1500 cap — early stopping never fired,
    so the v1 model was plausibly undertrained.)
  - All other hyperparameters identical to v1 (manual, fixed seed, no
    AutoML); identical 549-feature transform from common.py.

Validation:
  - v2 sets (val_random / val_site / val_period, same split protocol as
    v1, generated by simulate_v2.py) PLUS the new val_long set (forced
    long events only). B0, the v1 model and the v2 model are all scored
    on every v2 set -> direct v1 vs v2 comparison on identical sets.
  - The v2 model is also scored on the original v1 sets (backward check).
  - Trains ONLY on synthetic mixes. Nothing is fitted, calibrated or
    tuned on Test.csv; test inference uses the identical fixed feature
    transform. score_added_vessel = sqrt(share), as in v1.
"""
import json
import platform
import numpy as np
import pandas as pd
import lightgbm as lgb
import sklearn
import scipy
from common import DATA, ROOT, SEED, featurize_batch

MODEL_DIR = ROOT / "models"
MODEL_DIR.mkdir(exist_ok=True)
rng = np.random.default_rng(SEED)

PARAMS = dict(objective="regression", metric="rmse", learning_rate=0.05,
              num_leaves=63, min_data_in_leaf=40, feature_fraction=0.85,
              bagging_fraction=0.85, bagging_freq=1, lambda_l2=1.0,
              seed=SEED, verbose=-1, num_threads=2)
NUM_ROUNDS = 6000
ES_PATIENCE = 200

V2_SETS = ["val_random", "val_site", "val_period", "val_long"]
V1_SETS = ["val_random", "val_site", "val_period"]


def load(prefix, name):
    d = np.load(DATA / f"{prefix}_{name}.npz", allow_pickle=True)
    return d["X"], d["y"].astype(np.float64), d["site"], d["kind"]


def load_features(tag, X):
    cache = DATA / f"feat_{tag}.npz"
    if cache.exists():
        d = np.load(cache, allow_pickle=True)
        return d["F"], list(d["names"])
    F, names = featurize_batch(X)
    np.savez_compressed(cache, F=F, names=np.array(names))
    return F, names


def rmse(a, b):
    return float(np.sqrt(np.mean((np.asarray(a) - np.asarray(b)) ** 2)))


def pressure_maps(X, y, sites, pred):
    bands = [(0.0, 0.0), (0.0, 0.1), (0.1, 0.3), (0.3, 0.6), (0.6, 1.0)]
    pm = {}
    for lo, hi in bands:
        m = (y == 0) if hi == 0.0 else ((y > lo) & (y <= hi))
        if m.sum() > 0:
            pm[f"{lo}-{hi}"] = dict(n=int(m.sum()), rmse=rmse(pred[m], y[m]))
    by_site = {}
    for s in np.unique(sites):
        m = sites == s
        if m.sum() >= 30:
            by_site[str(s)] = dict(n=int(m.sum()), rmse=rmse(pred[m], y[m]))
    nmiss = np.isnan(X).any(axis=2).sum(axis=1)
    by_miss = {}
    for k in [0, 1, 2]:
        m = nmiss == k if k < 2 else nmiss >= 2
        if m.sum() > 0:
            by_miss[str(k)] = dict(n=int(m.sum()), rmse=rmse(pred[m], y[m]))
    return dict(by_share_band=pm, by_site=by_site, by_n_missing_minutes=by_miss)


def score_entry(y, pred):
    return dict(rmse=rmse(pred, y), score=1 - rmse(pred, y),
                null_mean_pred=float(pred[y == 0].mean()) if (y == 0).any() else None)


def main():
    versions = dict(python=platform.python_version(), numpy=np.__version__,
                    pandas=pd.__version__, scipy=scipy.__version__,
                    lightgbm=lgb.__version__, sklearn=sklearn.__version__)
    print("versions:", versions, flush=True)

    Xtr, ytr, _, _ = load("sim_v2", "train")
    print("featurizing v2 train...", flush=True)
    Ftr, names = load_features("v2_train", Xtr)
    print("features:", Ftr.shape, flush=True)

    best_iter_file = MODEL_DIR / "lgbm_sim_v2_best_iter.txt"
    model_path = MODEL_DIR / "lgbm_sim_v2.txt"
    if model_path.exists() and best_iter_file.exists():
        # Resume path: the saved file is already trimmed to the best
        # iteration, so predictions need no num_iteration argument.
        model = lgb.Booster(model_file=str(model_path))
        best_iter = int(best_iter_file.read_text())
        v2_kw = {}
        print("loaded existing v2 model; best iteration:", best_iter, flush=True)
    else:
        perm = rng.permutation(len(Ftr))
        cut = int(0.9 * len(Ftr))
        tri, vai = perm[:cut], perm[cut:]
        dtrain = lgb.Dataset(Ftr[tri], ytr[tri], feature_name=names)
        dval = lgb.Dataset(Ftr[vai], ytr[vai], reference=dtrain)
        model = lgb.train(PARAMS, dtrain, num_boost_round=NUM_ROUNDS,
                          valid_sets=[dval],
                          callbacks=[lgb.early_stopping(ES_PATIENCE, verbose=False)])
        best_iter = int(model.best_iteration)
        print("best iteration:", best_iter, "of cap", NUM_ROUNDS, flush=True)
        model.save_model(str(model_path), num_iteration=best_iter)
        best_iter_file.write_text(str(best_iter))
        imp = pd.Series(model.feature_importance("gain"), index=names)
        imp.sort_values(ascending=False).to_csv(MODEL_DIR / "lgbm_sim_v2_importance.csv")
        v2_kw = dict(num_iteration=best_iter)

    model_v1 = lgb.Booster(model_file=str(MODEL_DIR / "lgbm_sim_v1.txt"))

    def predict(m, F, best=None):
        kw = dict(num_iteration=best) if best else {}
        return np.clip(m.predict(F, **kw), 0, 1)

    results = dict(
        versions=versions, seed=SEED,
        training=dict(num_boost_round_cap=NUM_ROUNDS, es_patience=ES_PATIENCE,
                      best_iteration=best_iter,
                      params={k: v for k, v in PARAMS.items()}),
        v2_sets={}, v1_sets={})

    for name in V2_SETS:
        X, y, sites, _ = load("sim_v2", name)
        F, _ = load_features(f"v2_{name}", X)
        b0 = np.full_like(y, 0.1)
        p1 = predict(model_v1, F)
        p2 = np.clip(model.predict(F, **v2_kw), 0, 1)
        entry = dict(n=int(len(y)),
                     b0=dict(rmse=rmse(b0, y), score=1 - rmse(b0, y)),
                     v1_model=score_entry(y, p1),
                     v2_model=score_entry(y, p2))
        entry["v2_model"].update(pressure_maps(X, y, sites, p2))
        entry["v1_model"].update(pressure_maps(X, y, sites, p1))
        results["v2_sets"][name] = entry
        print(f"v2 set {name}: B0 {entry['b0']['score']:.4f} | "
              f"v1 model {entry['v1_model']['score']:.4f} | "
              f"v2 model {entry['v2_model']['score']:.4f}", flush=True)

    for name in V1_SETS:
        X, y, sites, _ = load("sim", name)
        F, _ = load_features(name, X)          # v1 caches from the v1 run
        b0 = np.full_like(y, 0.1)
        p1 = predict(model_v1, F)
        p2 = np.clip(model.predict(F, **v2_kw), 0, 1)
        entry = dict(n=int(len(y)),
                     b0=dict(rmse=rmse(b0, y), score=1 - rmse(b0, y)),
                     v1_model=score_entry(y, p1),
                     v2_model=score_entry(y, p2))
        results["v1_sets"][name] = entry
        print(f"v1 set {name}: B0 {entry['b0']['score']:.4f} | "
              f"v1 model {entry['v1_model']['score']:.4f} | "
              f"v2 model {entry['v2_model']['score']:.4f}", flush=True)

    (MODEL_DIR / "sim_v2_validation.json").write_text(json.dumps(results, indent=1))

    # Test inference with the v2 model (fixed transform only).
    test = pd.read_csv(DATA / "Test.csv", dtype={"ID": str})
    fcols = [c for c in test.columns if c != "ID"]
    Xt = test[fcols].to_numpy(dtype=np.float32).reshape(-1, 15, 25)
    Ft, _ = load_features("test", Xt)
    share2 = np.clip(model.predict(Ft, **v2_kw), 0, 1)
    sub = pd.DataFrame(dict(ID=test["ID"], share_added_vessel=share2,
                            score_added_vessel=np.sqrt(share2)))
    out = ROOT / "submissions" / "submission_sim_v2.csv"
    sub.to_csv(out, index=False)

    share1 = pd.read_csv(ROOT / "submissions" / "submission_sim_v1.csv")[
        "share_added_vessel"].to_numpy()
    dist = {}
    for tag, s in [("v1", share1), ("v2", share2)]:
        dist[tag] = dict(mean=float(s.mean()), median=float(np.median(s)),
                         frac_below_0p05=float((s < 0.05).mean()),
                         deciles=np.percentile(s, [10, 25, 50, 75, 90]).round(4).tolist())
    results["test_prediction_distribution"] = dist
    (MODEL_DIR / "sim_v2_validation.json").write_text(json.dumps(results, indent=1))
    print("wrote", out)
    print("test prediction distribution:", json.dumps(dist, indent=1))


if __name__ == "__main__":
    main()
